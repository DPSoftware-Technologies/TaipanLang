// taipan_main.cpp - the standalone runner: `taipan script.tp`
//
// A host like any game engine, except it registers the standalone-only
// built-ins (input, time.sleep, file.*) and drives coroutines with the real
// clock until they all finish.
#include "taipan.h"

#include <chrono>
#include <cstdio>
#include <cstring>
#include <string>
#include <thread>
#include <vector>

static void usage() {
    std::printf(
        "Taipan %s - game scripting language\n"
        "\n"
        "usage: taipan [options] script.tp\n"
        "\n"
        "options:\n"
        "  --check         type-check only, do not run\n"
        "  --no-cache      do not read or write the bytecode cache\n"
        "  --cache-dir D   bytecode cache directory (default: <temp>/taipan_cache)\n"
        "  --no-warnings   hide warnings\n"
        "  --bindings F    load a binding stub file (.tpi) declaring a host's native API\n"
        "  --disasm        print the generated bytecode\n"
        "  --gc-stress     run the garbage collector at every safepoint (debugging)\n"
        "  --gc-tiny       tiny GC thresholds to exercise incremental collection\n"
        "  --gc-stats      print collector statistics at exit\n"
        "  --version       print the version\n",
        TAIPAN_VERSION);
}

int main(int argc, char** argv) {
    const char* script = nullptr;
    bool check = false, cache = true, warnings = true, disasm = false, stress = false, tiny = false, stats = false;
    const char* cacheDir = nullptr;
    std::vector<const char*> bindings;
    for (int i = 1; i < argc; i++) {
        const char* a = argv[i];
        if (!std::strcmp(a, "--check")) check = true;
        else if (!std::strcmp(a, "--no-cache")) cache = false;
        else if (!std::strcmp(a, "--cache-dir") && i + 1 < argc) cacheDir = argv[++i];
        else if (!std::strcmp(a, "--no-warnings")) warnings = false;
        else if (!std::strcmp(a, "--bindings") && i + 1 < argc) bindings.push_back(argv[++i]);
        else if (!std::strcmp(a, "--disasm")) disasm = true;
        else if (!std::strcmp(a, "--gc-stress")) stress = true;
        else if (!std::strcmp(a, "--gc-tiny")) tiny = true;
        else if (!std::strcmp(a, "--gc-stats")) stats = true;
        else if (!std::strcmp(a, "--version")) {
            std::printf("Taipan %s\n", TAIPAN_VERSION);
            return 0;
        } else if (!std::strcmp(a, "--help") || !std::strcmp(a, "-h")) {
            usage();
            return 0;
        } else if (a[0] == '-' && a[1] == '-') {
            std::fprintf(stderr, "unknown option '%s'\n", a);
            return 64;
        } else if (!script) {
            script = a;
        }
    }
    if (!script) {
        usage();
        return 64;
    }

    TaipanState* state = taipan_create();
    taipan_open_standalone(state);
    taipan_set_bytecode_cache(state, cache && !disasm, cacheDir);
    taipan_set_warnings(state, warnings);
    taipan_set_dump_bytecode(state, disasm);
    taipan_set_gc_stress(state, stress);
    taipan_set_gc_tiny(state, tiny);
    for (const char* b : bindings) {
        if (!taipan_load_bindings(state, b)) {
            taipan_destroy(state);
            return 1;
        }
    }

    if (check) {
        bool ok = taipan_check_file(state, script);
        if (ok) std::printf("%s: no errors\n", script);
        taipan_destroy(state);
        return ok ? 0 : 1;
    }

    if (!taipan_load_file(state, script)) {
        taipan_destroy(state);
        return 1;
    }
    bool ok = taipan_run(state);

    // Drive running coroutines in real time until they are all done.
    auto last = std::chrono::steady_clock::now();
    while (ok && taipan_coroutine_count(state) > 0) {
        double next = taipan_next_wake(state);
        if (next > 0) std::this_thread::sleep_for(std::chrono::duration<double>(next < 0.25 ? next : 0.25));
        auto now = std::chrono::steady_clock::now();
        taipan_update(state, std::chrono::duration<double>(now - last).count());
        last = now;
    }
    if (!taipan_last_error(state).empty()) ok = false;
    if (stats) std::fprintf(stderr, "%s\n", taipan_gc_stats(state).c_str());
    taipan_destroy(state);
    return ok ? 0 : 1;
}
